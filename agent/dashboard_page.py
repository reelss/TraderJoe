"""Builds a self-contained dashboard.html from Joe's logs + live account.

Single file, no CDN/network needed: inline CSS, vanilla JS, inline-SVG equity
curve. Data is injected as a JSON blob. Regenerated by `scripts/build_dashboard.py`
and at the end of the daily digest run.
"""
from __future__ import annotations

import json
from datetime import datetime, timezone

from . import logbook as log
