def _read_jsonl(path) -> list[dict]:
    out = []
    if path.exists():
        for line in path.read_text(encoding="utf-8").splitlines():
            line = line.strip()
            if line:
                try:
                    out.append(json.loads(line))
                except json.JSONDecodeError:
                    pass
    return out


def _gather() -> dict:
    equity_log = _read_jsonl(log.EQUITY)
    trades = _read_jsonl(log.TRADES)
    decisions = _read_jsonl(log.DECISIONS)

    # Live account/positions; fall back to last logged values if broker is down.
    account, positions = None, []
    alpaca_fills = {}  # symbol -> [(side, qty, price, ts), ...]
    try:
        from .broker import Broker
        from alpaca.trading.requests import GetOrdersRequest
        from alpaca.trading.enums import QueryOrderStatus

        b = Broker()
        account = b.account()
        positions = b.positions()

        # Fetch closed orders to get fill prices
        try:
            orders = b.trading.get_orders(
                GetOrdersRequest(status=QueryOrderStatus.CLOSED, limit=500)
            )
            for o in orders:
                if o.symbol not in alpaca_fills:
                    alpaca_fills[o.symbol] = []
                if float(o.filled_qty or 0) > 0:
                    alpaca_fills[o.symbol].append({
                        "side": str(o.side).split(".")[-1].lower(),
                        "qty": float(o.filled_qty),
                        "price": float(o.filled_avg_price) if o.filled_avg_price else None,
                        "ts": o.filled_at.isoformat() if o.filled_at else "",
                    })
        except Exception as exc:
            log.info(f"dashboard: alpaca fills unavailable ({exc!r})")
    except Exception as exc:
        log.info(f"dashboard: broker unavailable, using logs ({exc!r})")

    start = RISK.starting_equity
    if account:
        equity = account["equity"]
        cash = account["cash"]
        last_equity = account["last_equity"] or equity
    elif equity_log:
        equity = equity_log[-1].get("equity", start)
        cash = equity_log[-1].get("cash", 0.0)
        last_equity = equity
    else:
        equity, cash, last_equity = start, start, start

    # Equity curve: baseline + every logged snapshot (capped to the last 500).
    curve = [{"t": "start", "v": start}]
    for e in equity_log[-500:]:
        curve.append({"t": e.get("ts", ""), "v": e.get("equity", start)})
    if account:
        curve.append({"t": datetime.now(timezone.utc).isoformat(), "v": equity})

    winners = sum(1 for p in positions if p["unrealized_plpc"] > 0)
    win_rate = (winners / len(positions)) if positions else None

    # Enrich trades with Alpaca fill data: add buy/sell prices and realized P&L
    enriched_trades = []
    for t in reversed(trades):
        if t.get("status") == "error":
            continue
        t_out = t.copy()
        symbol = t.get("symbol", "")
        fills = alpaca_fills.get(symbol, [])

        # Match this trade to a fill by symbol + side + time proximity
        if fills:
            side = t.get("side", "").lower()
            # Find the closest fill in time
            closest = None
            closest_diff = float("inf")
            for fill in fills:
                if fill["side"] == side:
                    ts_str = t.get("ts", "")
                    if ts_str and fill["ts"]:
                        try:
                            t_dt = datetime.fromisoformat(ts_str.replace("Z", "+00:00"))
                            f_dt = datetime.fromisoformat(fill["ts"].replace("Z", "+00:00"))
                            diff = abs((t_dt - f_dt).total_seconds())
                            if diff < closest_diff:
                                closest_diff = diff
                                closest = fill
                        except ValueError:
                            pass
            if closest and closest_diff < 3600:  # within 1 hour
                t_out["fill_price"] = closest["price"]
                t_out["fill_qty"] = closest["qty"]

        enriched_trades.append(t_out)

    # Pair up buy/sell trades to calculate realized P&L
    paired = {}  # symbol -> {"buy": [...], "sell": [...]}
    for t in enriched_trades:
        sym = t.get("symbol", "")
        if sym not in paired:
            paired[sym] = {"buy": [], "sell": []}
        side = t.get("side", "").lower()
        if side in ["buy", "sell"]:
            paired[sym][side].append(t)

    # Calculate realized P&L for closed pairs
    for t in enriched_trades:
        sym = t.get("symbol", "")
        side = t.get("side", "").lower()
        if side == "sell" and "fill_price" in t and sym in paired:
            # Look for matching buy before this sell
            buys = [b for b in paired[sym]["buy"] if b.get("ts", "") < t.get("ts", "")]
            if buys:
                buy = buys[-1]  # most recent buy before sell
                if "fill_price" in buy:
                    qty = min(t.get("fill_qty", 0), buy.get("fill_qty", 0))
                    t["realized_pl"] = (t["fill_price"] - buy["fill_price"]) * qty
                    t["matched_buy_ts"] = buy.get("ts", "")

    return {
        "generated": datetime.now(timezone.utc).isoformat(),
        "start_equity": start,
        "equity": equity,
        "cash": cash,
        "day_pl": equity - last_equity,
        "day_pct": ((equity - last_equity) / last_equity) if last_equity else 0.0,
        "total_pl": equity - start,
        "total_pct": (equity - start) / start,
        "open_count": len(positions),
        "win_rate": win_rate,
        "winners": winners,
        "positions": [
            {
                "symbol": p["symbol"], "qty": p["qty"],
                "avg_entry": p["avg_entry"], "current_price": p["current_price"],
                "market_value": p["market_value"], "plpc": p["unrealized_plpc"] * 100,
                "pl": p["unrealized_pl"],
            } for p in positions
        ],
        "curve": curve,
        "trades": enriched_trades[:25],
        "decisions": list(reversed(decisions))[:30],
    }


def build_dashboard() -> str:
    data = _gather()
    html = _TEMPLATE.replace("/*__DATA__*/null", json.dumps(data, default=str))
    out = ROOT / "dashboard.html"
    out.write_text(html, encoding="utf-8")
    log.info(f"Dashboard written: {out}")
    return str(out)


